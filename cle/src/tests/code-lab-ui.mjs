import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import ts from 'typescript'
const source=readFileSync(new URL('../lib/codeLab.ts',import.meta.url),'utf8')
const js=ts.transpile(source,{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022})
const lib=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'))
assert.deepEqual(lib.occurrences({steps:[{line:2},{line:3},{line:2}]},2),[0,2])
assert.equal(lib.arrayScale([-5,2,0]),5)
assert.equal(lib.arrayScale([]),1)
assert.equal(lib.valueText([3,2]),'[3,2]')
const svg=lib.traceSvg({steps:[{line:2,event:'statement',frames:[{name:'<module>',variables:{x:'<script>alert(1)</script>'}}]}]},0)
assert(!svg.includes('<script>'));assert(svg.includes('&lt;script&gt;'));assert(svg.includes('&lt;module&gt;'))
assert.equal(lib.traceSvg({steps:[]},0),'')
for(const sample of Object.values(lib.samples)){assert(sample.source.length<16000);assert(Array.isArray(JSON.parse(sample.args)))}
assert.deepEqual(JSON.parse(readFileSync(new URL('../../../src/code-lab/samples.json',import.meta.url),'utf8')),lib.samples)
const java='class Test { public static void main(String[] args) { int n = 8; } }'
assert.deepEqual(lib.mainSetupHint(java,'auto','sort','[[5,2,8,1]]'),{language:'java',reason:'entry'})
assert.deepEqual(lib.mainSetupHint(java,'java','main','[[5,2,8,1]]'),{language:'java',reason:'arguments'})
assert.deepEqual(lib.mainSetupHint(java,'auto','','[[5,2,8,1]]'),{language:'java',reason:'arguments'})
for(const args of ['[]','[[]]','[["hello","world"]]'])assert.equal(lib.mainSetupHint(java,'auto','main',args),undefined)
assert.equal(lib.mainSetupHint(java,'python','sort','[]'),undefined)
assert.equal(lib.mainSetupHint(java,'c','sort','[]'),undefined)
assert.equal(lib.mainSetupHint(java+' static int[] sort(int[] a) { return a; }','java','sort','[[1]]'),undefined)
assert.equal(lib.mainSetupHint('/* '+java+' */ int sum(){return 1;}','auto','sort','[]'),undefined)
assert.equal(lib.mainSetupHint('String s = "'+java+'";','auto','sort','[]'),undefined)
assert.equal(lib.mainSetupHint('# '+java,'auto','sort','[]'),undefined)
assert.deepEqual(lib.mainSetupHint('int main(void){return 0;}','auto','sort','[[1]]'),{language:'c',reason:'entry'})
assert.equal(lib.mainSetupHint('int main(int argc, char** argv){return 0;}','c','sort','[]'),undefined)
assert.equal(lib.mainSetupHint(java,'java','main','{bad'),undefined)
const run={source:java,entry:'main',arguments:[],result:{language:'java'}}
assert.equal(lib.replayMatchesEditor(run,java,'main','[ ]','auto'),true)
assert.equal(lib.replayMatchesEditor(run,java,'sort','[]','auto'),false)
assert.equal(lib.replayMatchesEditor(run,java,'main','[[1]]','auto'),false)
assert.equal(lib.replayMatchesEditor(run,java+' ','main','[]','auto'),false)
assert.equal(lib.replayMatchesEditor(run,java,'main','[]','c'),false)
console.log('Code lab helpers: replay, SVG, examples, main setup guidance and stale result checks passed')
